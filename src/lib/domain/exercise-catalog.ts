// Catálogo curado inicial (v2): fichas detalhadas por exercício.
// - Exercícios que já existiam mantêm o ID (treinos antigos continuam resolvendo);
//   o nome anterior vira apelido pesquisável.
// - Papéis musculares descrevem contribuições anatômicas típicas e mudam com a
//   execução. Não são medidas de ativação nem promessa de hipertrofia.
// - Toda ficha começa "pendente de revisão editorial".
