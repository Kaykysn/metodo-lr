import type { Modality, MovementPattern } from "./exercise-library";

export type Purpose = "hipertrofia" | "reabilitacao";
export const PURPOSE_LABEL: Record<Purpose, string> = { hipertrofia: "Hipertrofia", reabilitacao: "Reabilitação / retorno ao exercício" };

export type MuscleRoleKind = "primary" | "secondary" | "stabilizer";
export const ROLE_LABEL: Record<MuscleRoleKind, string> = { primary: "Principal", secondary: "Secundário", stabilizer: "Estabilizador" };

export type Laterality = "bilateral" | "unilateral" | "alternado";
export const LATERALITY_LABEL: Record<Laterality, string> = { bilateral: "Bilateral", unilateral: "Unilateral", alternado: "Alternado" };

export type Difficulty = "iniciante" | "intermediário" | "avançado";

export type PrescriptionField = "séries" | "repetições" | "carga externa" | "esforço" | "descanso" | "cadência" | "amplitude" | "tempo de sustentação";

export interface MuscleRole {
  /** ID de músculo ou de grupo (muscles.ts). */
  ref: string;
  role: MuscleRoleKind;
  note?: string;
}

export interface ExerciseDetail {
  variation: string;
  muscles: MuscleRole[];
  jointActions: string[];
  startingPosition: string;
  instructions: string[];
  breathing: string;
  adjustments: string[];
  /** Como o papel dos músculos muda com posição, apoio e amplitude. */
  roleVariation: string;
  purposeNotes: Partial<Record<Purpose, string>>;
  prescriptionFields: PrescriptionField[];
  /** Sintomas e tolerância em contexto de retorno ao exercício. */
  toleranceNotes: string;
  /** IDs de afirmações (evidence-claims.ts). */
  claims: string[];
  /** Referências ainda não localizadas, mostradas como pendentes. */
  pendingReferences: string[];
  media: { status: "sem mídia autorizada"; source: null; rights: null };
  reviewStatus: "pendente de revisão editorial";
}

export interface CatalogEntry {
  id: string;
  name: string;
  aliases: string[];
  englishNames: string[];
  pattern: MovementPattern;
  modality: Modality;
  loadKind: "external_kg" | "bodyweight" | "band" | "pilates_springs" | "time_or_distance";
  equipment: string[];
  laterality: Laterality;
  difficulty: Difficulty;
  purposes: Purpose[];
  objective: string;
  commonErrors: string;
  precautions: string;
  regressions: string[];
  progressions: string[];
  detail: ExerciseDetail;
}

