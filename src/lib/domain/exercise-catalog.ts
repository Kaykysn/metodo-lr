// Atalhos de redação
// ---------------------------------------------------------------------------
type R = [string, MuscleRoleKind, string?];
const RT: PrescriptionField[] = ["séries", "repetições", "carga externa", "esforço", "descanso", "cadência", "amplitude"];
const BW: PrescriptionField[] = ["séries", "repetições", "esforço", "descanso", "cadência", "amplitude"];
const ISO: PrescriptionField[] = ["séries", "tempo de sustentação", "esforço", "descanso", "amplitude"];

const TOL =
  "Registrar sintomas durante e até 24 h depois, separados do esforço. Amplitude tolerada, critério de progressão e critério de interrupção são definidos pelo profissional para o caso; esta ficha não traz corte de dor universal.";
const HYP =
  "Para hipertrofia, séries, proximidade da falha e carga são definidas pelo professor conforme a pessoa e a fase. A ficha descreve a execução; não define dose.";
const ADV_PRECAUTION = "Exige técnica estável e carga escolhida pelo professor. Interromper e reavaliar se houver dor que mude a execução.";
const TRUNK_REF = "Referência anatômica dos músculos do tronco (OpenStax, cap. 11.4) ainda não registrada.";
const LOWER = "anat-membro-inferior";
const UPPER = "anat-membro-superior";

interface Draft {
  id: string;
  name: string;
  aliases?: string[];
  en?: string[];
  pattern: MovementPattern;
  modality: Modality;
  loadKind: CatalogEntry["loadKind"];
  equipment: string[];
  laterality: Laterality;
  difficulty: Difficulty;
  purposes: Purpose[];
  objective: string;
  variation: string;
  muscles: R[];
  joints: string[];
  start: string;
  steps: string[];
  breathing?: string;
  adjust: string[];
  roleVariation: string;
  notes: Partial<Record<Purpose, string>>;
  fields?: PrescriptionField[];
  tolerance?: string;
  errors: string;
  precautions?: string;
  regressions?: string[];
  progressions?: string[];
  claims: string[];
  pending?: string[];
}

function x(d: Draft): CatalogEntry {
  return {
    id: d.id,
    name: d.name,
    aliases: d.aliases ?? [],
    englishNames: d.en ?? [],
    pattern: d.pattern,
    modality: d.modality,
    loadKind: d.loadKind,
    equipment: d.equipment,
    laterality: d.laterality,
    difficulty: d.difficulty,
    purposes: d.purposes,
    objective: d.objective,
    commonErrors: d.errors,
    precautions: d.precautions ?? (d.purposes.includes("reabilitacao") ? TOL : ADV_PRECAUTION),
    regressions: d.regressions ?? [],
    progressions: d.progressions ?? [],
    detail: {
      variation: d.variation,
      muscles: d.muscles.map(([ref, role, note]) => ({ ref, role, ...(note ? { note } : {}) })),
      jointActions: d.joints,
      startingPosition: d.start,
      instructions: d.steps,
      breathing: d.breathing ?? "Expirar na fase de maior esforço e inspirar no retorno, sem prender o ar por tempo prolongado.",
      adjustments: d.adjust,
      roleVariation: d.roleVariation,
      purposeNotes: d.notes,
      prescriptionFields: d.fields ?? (d.loadKind === "external_kg" ? RT : d.loadKind === "time_or_distance" ? ["séries", "repetições", "tempo de sustentação", "descanso", "amplitude"] : BW),
      toleranceNotes: d.tolerance ?? TOL,
      claims: d.claims,
      pendingReferences: d.pending ?? [],
      media: { status: "sem mídia autorizada", source: null, rights: null },
      reviewStatus: "pendente de revisão editorial",
    },
  };
}

